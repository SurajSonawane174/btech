"""
evaluation/run_evaluation.py -- score extractor output against hand-labelled ground truth.

    python evaluation/run_evaluation.py --name <dataset> --kind synthetic|real
        --gold gold_comments.csv --pred output/master_comments.csv
        [--retrieval-gold gold_retrieval.csv --retrieval-results retrieval_results.json | --live-retrieval]
        [--k 3] [--match-threshold 90] [--out evaluation_report.json]

Formats are documented in evaluation/README.md; empty templates are in evaluation/templates/.
--kind is mandatory and is copied into the report: "real" means the gold file was labelled by a
person from real drawings; anything generated by code is "synthetic". The report keeps one entry
per --name, so several datasets can be scored into the same file. If no dataset of kind "real"
is present, the report says real-world metrics are unavailable.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path
from typing import Dict, List

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from evaluation import metrics as M  # noqa: E402

GOLD_REQUIRED = ["source_file", "page", "comment_text"]
GOLD_OPTIONAL = ["category", "duplicate_group"]
PRED_REQUIRED = ["source_file", "page_sheet", "actual_extracted_comment", "comment_id"]
RETRIEVAL_REQUIRED = ["query_text", "relevant_comment_text"]


class FormatError(ValueError):
    pass


def read_csv_text(path) -> pd.DataFrame:
    """All cells as text; only empty cells are missing (keeps a literal 'NA')."""
    return pd.read_csv(path, dtype=str, keep_default_na=False, na_values=[""]).fillna("")


def _require(df: pd.DataFrame, cols: List[str], what: str) -> None:
    missing = [c for c in cols if c not in df.columns]
    if missing:
        raise FormatError(f"{what} is missing column(s): {', '.join(missing)}")


def load_gold(path) -> pd.DataFrame:
    df = read_csv_text(path)
    _require(df, GOLD_REQUIRED, f"gold file {Path(path).name}")
    blank = df["comment_text"].str.strip() == ""
    if blank.any():
        raise FormatError(f"gold file has {int(blank.sum())} row(s) with empty comment_text")
    return df


def load_pred(path) -> pd.DataFrame:
    df = read_csv_text(path)
    _require(df, PRED_REQUIRED, f"prediction file {Path(path).name}")
    return df


def evaluate(gold: pd.DataFrame, pred: pd.DataFrame, threshold: float = 90.0) -> Dict:
    g_items = [{"source_file": r.source_file, "page": str(r.page).strip(), "text": r.comment_text}
               for r in gold.itertuples()]
    p_items = [{"source_file": r.source_file, "page": str(r.page_sheet).strip(), "text": r.actual_extracted_comment}
               for r in pred.itertuples()]
    out = {"extraction": M.extraction_metrics(p_items, g_items, threshold)}
    matches = M.match_comments(p_items, g_items, threshold) if g_items else []

    # classification on matched comments only (a missed comment is an extraction error, not a class error)
    if "category" in gold.columns and (gold["category"].str.strip() != "").any():
        pred_cat = pred["comment_category"] if "comment_category" in pred.columns else pd.Series([""] * len(pred))
        out["classification"] = M.classification_metrics(
            (gold["category"].iloc[gi], pred_cat.iloc[pi]) for pi, gi, _ in matches)
        out["classification"]["unmatched_gold_with_label"] = int(
            (gold["category"].str.strip() != "").sum()) - out["classification"].get("n", 0)
    else:
        out["classification"] = {"status": "no_labels"}

    # duplicates: both sides restricted to matched comments, expressed as gold row indices
    labelled = "duplicate_group" in gold.columns
    p2g = {pi: gi for pi, gi, _ in matches}
    matched_g = set(p2g.values())
    if labelled:
        groups: Dict[str, set] = {}
        for gi, r in enumerate(gold.itertuples()):
            if r.duplicate_group.strip() and gi in matched_g:
                groups.setdefault((r.source_file, r.duplicate_group.strip()), set()).add(gi)
        gold_pairs = M.pairs_from_groups(groups)
        all_groups: Dict[str, set] = {}
        for gi, r in enumerate(gold.itertuples()):
            if r.duplicate_group.strip():
                all_groups.setdefault((r.source_file, r.duplicate_group.strip()), set()).add(gi)
        excluded = len(M.pairs_from_groups(all_groups)) - len(gold_pairs)
        id_to_p = {cid: pi for pi, cid in enumerate(pred["comment_id"]) if cid}
        links, dropped = [], 0
        if "duplicate_of" in pred.columns:
            for pi, target in enumerate(pred["duplicate_of"]):
                if not target:
                    continue
                ti = id_to_p.get(target)
                if pi in p2g and ti in p2g:
                    links.append((p2g[pi], p2g[ti]))
                else:
                    dropped += 1
        out["duplicates"] = M.duplicate_metrics(M.pairs_from_links(links), gold_pairs, True)
        out["duplicates"].update({"gold_pairs_excluded_unmatched": excluded, "pred_links_dropped_unmatched": dropped})
    else:
        out["duplicates"] = M.duplicate_metrics(set(), set(), False)
    return out


def load_retrieval_gold(path) -> Dict[str, set]:
    df = read_csv_text(path)
    _require(df, RETRIEVAL_REQUIRED, f"retrieval gold file {Path(path).name}")
    rel: Dict[str, set] = {}
    for r in df.itertuples():
        q = M.normalize_text(r.query_text)
        if not q:
            continue
        rel.setdefault(q, set())
        if M.normalize_text(r.relevant_comment_text):
            rel[q].add(M.normalize_text(r.relevant_comment_text))
    return rel


def load_retrieval_results(path) -> Dict[str, List[str]]:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(data, dict) or not all(isinstance(v, list) for v in data.values()):
        raise FormatError("retrieval results must be a JSON object {query_text: [comment_text, ...]}")
    return {M.normalize_text(q): [M.normalize_text(t) for t in v] for q, v in data.items()}


def live_retrieval_results(queries: List[str], k: int) -> Dict[str, List[str]]:
    """Runs the REAL embedder + Qdrant search (needs Ollama and Qdrant). Unscoped, no threshold."""
    from vectordb import embedder
    from vectordb.qdrant_client import search_similar_comments
    return {q: [M.normalize_text(h["text"]) for h in
                search_similar_comments(embedder.embed_text(q), top_k=k, score_threshold=0.0)]
            for q in queries}


def merge_report(out_path: Path, entry: Dict) -> Dict:
    report = {"datasets": []}
    if out_path.exists():
        report = json.loads(out_path.read_text(encoding="utf-8"))
    report["datasets"] = [d for d in report.get("datasets", []) if d.get("name") != entry["name"]] + [entry]
    report["generated"] = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    real = [d["name"] for d in report["datasets"] if d.get("kind") == "real"]
    report["real_world_metrics"] = (f"available for: {', '.join(real)}" if real else
                                    "unavailable: no human-labelled real dataset has been evaluated")
    out_path.write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")
    return report


def main(argv=None) -> Dict:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True)
    ap.add_argument("--kind", required=True, choices=["synthetic", "real"])
    ap.add_argument("--gold", required=True)
    ap.add_argument("--pred", required=True)
    ap.add_argument("--retrieval-gold")
    src = ap.add_mutually_exclusive_group()
    src.add_argument("--retrieval-results")
    src.add_argument("--live-retrieval", action="store_true")
    ap.add_argument("--k", type=int, default=3)
    ap.add_argument("--match-threshold", type=float, default=90.0)
    ap.add_argument("--out", default=str(ROOT / "evaluation_report.json"))
    args = ap.parse_args(argv)

    metrics = evaluate(load_gold(args.gold), load_pred(args.pred), args.match_threshold)
    if args.retrieval_gold:
        rel = load_retrieval_gold(args.retrieval_gold)
        if args.live_retrieval:
            ranked, source = live_retrieval_results(list(rel), args.k), "live (Ollama + Qdrant)"
        elif args.retrieval_results:
            ranked, source = load_retrieval_results(args.retrieval_results), Path(args.retrieval_results).name
        else:
            ap.error("--retrieval-gold needs --retrieval-results or --live-retrieval")
        metrics["retrieval"] = {**M.retrieval_metrics(ranked, rel, args.k), "results_source": source}
    else:
        metrics["retrieval"] = {"status": "no_labels", "note": "no --retrieval-gold given"}

    entry = {"name": args.name, "kind": args.kind, "gold_file": Path(args.gold).name,
             "pred_file": Path(args.pred).name, "metrics": metrics}
    report = merge_report(Path(args.out), entry)
    print(json.dumps({"dataset": args.name, "kind": args.kind,
                      **{t: {k: v for k, v in m.items() if k in ("status", "precision", "recall", "f1", "accuracy",
                                                                   "macro_f1", "precision_at_k", "recall_at_k", "n")}
                         for t, m in metrics.items()}}, indent=2, default=str))
    print(f"real-world metrics: {report['real_world_metrics']}\nreport: {args.out}")
    return report


if __name__ == "__main__":
    main()
